#!/usr/bin/env node
// Regenerates extension/engines/tts/trnorm/*.js from Harfiyen's TypeScript trnorm (MIT), pinned to a commit:
// fetches src/tts/trnorm/*.ts from GitHub, strips the type annotations with Node's built-in
// module.stripTypeScriptTypes (no bundler, no dependency), fixes the relative import specifiers and prepends the
// attribution header. The output is plain ES modules that run unchanged in the browser and in Node.
//
//   node tools/tts/port-trnorm.mjs

import { stripTypeScriptTypes } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const COMMIT = '981902ceaef804fdb7a4edb782078c766e3b53c2';
const BASE = `https://raw.githubusercontent.com/ozcancelik/harfiyen/${COMMIT}/src/tts/trnorm/`;
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../../extension/engines/tts/trnorm');
const FILES = ['casing', 'lexicon', 'numbers', 'normalize'];

const HEADER = `// GENERATED by tools/tts/port-trnorm.mjs from Harfiyen src/tts/trnorm/{name}.ts @ ${COMMIT}
// https://github.com/ozcancelik/harfiyen — MIT License, Copyright (c) 2026 Özcan Çelik.
// Harfiyen's trnorm is itself a port of trnorm from ozguradmin/ahenk-turkish-tts (Apache-2.0).
// Only TypeScript types were removed; do not edit by hand (local additions live in ../normalize.js).
`;

for (const name of FILES) {
  const res = await fetch(BASE + name + '.ts');
  if (!res.ok) throw new Error(`${name}.ts: HTTP ${res.status}`);
  let js = stripTypeScriptTypes(await res.text(), { mode: 'strip' });
  js = js.replace(/from "\.\/(\w+)"/g, 'from "./$1.js"');
  // strip mode blanks the types out with spaces (to keep columns); tidy code lines (never comments)
  js = js
    .split('\n')
    .map((line) => {
      if (line.trimStart().startsWith('//')) return line;
      return line
        .replace(/(?<=\S) {2,}(?=[,;)\]:])/g, '')
        .replace(/(?<=\S) {2,}(?=\S)/g, ' ')
        .replace(/(?<=\S) +$/, '');
    })
    .filter((line, i, all) => !(line.trim() === '' && all[i - 1]?.trim() === '' && i > 0))
    .join('\n');
  await writeFile(resolve(OUT, name + '.js'), HEADER.replace('{name}', name) + js);
  console.log('wrote', name + '.js');
}
